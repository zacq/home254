function describe(s: Seed) {
  const cap = s.wash && s.dry ? `${s.wash}kg wash / ${s.dry}kg dry` : s.wash ? `${s.wash}kg wash` : s.dry ? `${s.dry}kg dry` : "";
  const feats = s.features?.length ? ` Key features: ${s.features.join(", ")}.` : "";
  return `${s.benefit} ${cap ? `Capacity: ${cap}. ` : ""}${s.energy ? `Energy rating ${s.energy}. ` : ""}${s.motor && s.motor !== "Standard" ? `Powered by a ${s.motor} motor for quieter, longer-lasting operation. ` : ""}${feats} Final price and availability are confirmed on WhatsApp before delivery.`.trim();
}

