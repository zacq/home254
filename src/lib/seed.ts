let seeded: Promise<void> | null = null;

export function ensureSeed() {
  if (!seeded) {
    seeded = runSeed().catch((e) => {
      seeded = null;
      throw e;
    });
  }
  return seeded;
}

async function runSeed() {
  // Idempotent: unique indexes + onConflictDoNothing make concurrent first-runs safe.
  const [{ n }] = await db.select({ n: sql<number>`count(*)::int` }).from(products);
  if (n === 0) {
    const offerEnd = new Date(Date.now() + 1000 * 60 * 60 * 24 * 30);
    await db
      .insert(products)
      .values(
        SEEDS.map((s) => ({
          name: s.name,
          brand: "MIKA",
          modelNumber: s.model,
          slug: slugify(`${s.name}-${s.model}`),
          category: s.category,
          type: s.type,
          washCapacityKg: s.wash ?? null,
          dryCapacityKg: s.dry ?? null,
          spinRpm: s.rpm ?? null,
          energyRating: s.energy ?? null,
          motor: s.motor ?? "Standard",
          features: s.features ?? [],
          warranty: s.warranty ?? GENERAL,
          priceKsh: s.price,
          offerPriceKsh: s.offer ?? null,
          offerStart: s.offer ? new Date() : null,
          offerEnd: s.offer ? offerEnd : null,
          offerBadge: s.offer ? "Launch offer" : null,
          stockQty: s.stock,
          lowStockAt: 2,
          colour: s.colour ?? null,
          dimensionsCm: s.dims ?? null,
          weightKg: s.weight ?? null,
          images: [CATEGORY_IMAGE[s.category]],
          shortBenefit: s.benefit,
          description: describe(s),
          featured: !!s.featured,
          popularity: s.pop ?? 0,
        })),
      )
      .onConflictDoNothing();
  }
  const [{ z }] = await db.select({ z: sql<number>`count(*)::int` }).from(deliveryZones);
  if (z === 0) await db.insert(deliveryZones).values(ZONES).onConflictDoNothing();
}
